def _plural(name: str) -> str:
    low = name.lower()
    if low.endswith("s"):
        return low + "es" if low.endswith("ss") else low
    if low.endswith("y"):
        return low[:-1] + "ies"
    return low + "s"


def _py_default(field_type: str) -> str:
    return {
        "string": '""',
        "text": '""',
        "integer": "0",
        "float": "0.0",
        "date": "None",
        "datetime": "None",
        "boolean": "False",
    }.get(field_type, '""')


def _py_type(field_type: str) -> str:
    return {
        "string": "str",
        "text": "str",
        "integer": "int",
        "float": "float",
        "date": "str",
        "datetime": "str",
        "boolean": "bool",
    }.get(field_type, "str")


def generate_security_py(app_name: str) -> str:
    return f'''"""Authentication utilities for {app_name} (generated by AgentForge Backend Agent)."""

import hashlib
import hmac
import os
import time

SECRET_KEY = os.environ.get("JWT_SECRET", "dev-secret-change-me")
TOKEN_TTL_SECONDS = 60 * 60 * 24 * 7
_ALGO = "sha256"


def hash_password(password: str) -> str:
    salt = os.urandom(16)
    digest = hashlib.pbkdf2_hmac(_ALGO, password.encode(), salt, 120_000)
    return salt.hex() + "$" + digest.hex()


def verify_password(password: str, stored: str) -> bool:
    try:
        salt_hex, digest_hex = stored.split("$", 1)
    except ValueError:
        return False
    digest = hashlib.pbkdf2_hmac(_ALGO, password.encode(), bytes.fromhex(salt_hex), 120_000)
    return hmac.compare_digest(digest.hex(), digest_hex)


def create_token(user_id: int) -> str:
    import json

    raw = json.dumps({{"sub": user_id, "exp": int(time.time()) + TOKEN_TTL_SECONDS}})
    sig = hmac.new(SECRET_KEY.encode(), raw.encode(), _ALGO).hexdigest()
    return raw + "." + sig


def decode_token(token: str):
    import json

    try:
        raw, sig = token.rsplit(".", 1)
        expected = hmac.new(SECRET_KEY.encode(), raw.encode(), _ALGO).hexdigest()
        if not hmac.compare_digest(sig, expected):
            return None
        payload = json.loads(raw)
        if payload.get("exp", 0) < time.time():
            return None
        return payload.get("sub")
    except (ValueError, json.JSONDecodeError):
        return None
'''


def generate_schemas_py(entities: list[dict], app_name: str) -> str:
    blocks = [
        f'"""Pydantic schemas for {app_name} (generated by AgentForge Backend Agent)."""',
        "from pydantic import BaseModel",
    ]
    for entity in entities:
        class_name = entity["name"]
        create_fields = []
        out_fields = ["    id: int"]
        for fname, ftype in entity.get("fields", []):
            py_t = _py_type(ftype)
            default = _py_default(ftype)
            if fname in ("password_hash", "password"):
                create_fields.append(f"    {fname}: str = \"\"")
                out_fields.append(f"    {fname}: str = \"\"")
                continue
            create_fields.append(f"    {fname}: {py_t} = {default}")
            out_fields.append(f"    {fname}: {py_t} = {default}")
        blocks.append(
            f"class {class_name}Create(BaseModel):\n" + "\n".join(create_fields)
            + f"\n\n\nclass {class_name}Out(BaseModel):\n" + "\n".join(out_fields)
        )
    return "\n\n\n".join(blocks) + "\n"


def _crud_code(entity: dict) -> str:
    class_name = entity["name"]
    # Route plural MUST equal the database table name: the React frontend's ENTITIES
    # config and the documented API contract both address collections by table name.
    plural = entity.get("table") or _plural(class_name)
    create_fields = [f for f, _ in entity.get("fields", [])]
    field_names = [f for f in create_fields if f != "password_hash"]
    model_kwargs = ", ".join(f"{f}=payload.{f}" for f in field_names if f not in ("id",))
    out_fields = ["id"] + [f for f in create_fields if f != "password_hash"]

    def _to_dict():
        pairs = ", ".join(f'"{f}": getattr(item, "{f}", None)' for f in out_fields)
        return pairs

    return f'''
# ---- {class_name} CRUD ----


@app.get("/api/{plural}")
def list_{plural}(db: Session = Depends(get_db), user_id: int = Depends(require_auth)):
    items = db.query({class_name}).all()
    return [{{{ _to_dict() }}} for item in items]


@app.post("/api/{plural}", status_code=201)
def create_{plural[:-1]}(payload: {class_name}Create, db: Session = Depends(get_db), user_id: int = Depends(require_auth)):
    item = {class_name}({model_kwargs})
    db.add(item)
    db.commit()
    db.refresh(item)
    return {{{ _to_dict() }}}


@app.get("/api/{plural}/{{item_id}}")
def get_{plural[:-1]}(item_id: int, db: Session = Depends(get_db), user_id: int = Depends(require_auth)):
    item = db.query({class_name}).filter({class_name}.id == item_id).first()
    if not item:
        raise HTTPException(status_code=404, detail="{class_name} not found")
    return {{{ _to_dict() }}}


@app.put("/api/{plural}/{{item_id}}")
def update_{plural[:-1]}(item_id: int, payload: {class_name}Create, db: Session = Depends(get_db), user_id: int = Depends(require_auth)):
    item = db.query({class_name}).filter({class_name}.id == item_id).first()
    if not item:
        raise HTTPException(status_code=404, detail="{class_name} not found")
    for f in {field_names!r}:
        if f != "id" and hasattr(payload, f):
            setattr(item, f, getattr(payload, f))
    db.commit()
    db.refresh(item)
    return {{{ _to_dict() }}}


@app.delete("/api/{plural}/{{item_id}}", status_code=204)
def delete_{plural[:-1]}(item_id: int, db: Session = Depends(get_db), user_id: int = Depends(require_auth)):
    item = db.query({class_name}).filter({class_name}.id == item_id).first()
    if not item:
        raise HTTPException(status_code=404, detail="{class_name} not found")
    db.delete(item)
    db.commit()
    return
'''


