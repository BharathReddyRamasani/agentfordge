"""Database Agent codegen: generates real schema.sql, seed.sql and SQLAlchemy models from the schema."""

FIELD_SQL_TYPES = {
    "string": "VARCHAR(255)",
    "text": "TEXT",
    "integer": "INTEGER",
    "float": "FLOAT",
    # Dates are stored as ISO-8601 strings (VARCHAR) so the same schema works
    # identically on SQLite and PostgreSQL without driver-level type binding.
    "date": "VARCHAR(32)",
    "datetime": "VARCHAR(32)",
    "boolean": "BOOLEAN",
}

FIELD_SA_TYPES = {
    "string": "String(255)",
    "text": "Text",
    "integer": "Integer",
    "float": "Float",
    "date": "String(32)",
    "datetime": "String(32)",
    "boolean": "Boolean",
}


def _table_name(entity: dict) -> str:
    # Idempotent: an explicitly provided table name is trusted as-is.
    if entity.get("table"):
        return entity["table"]
    name = entity["name"]
    snake = "".join("_" + c.lower() if c.isupper() else c for c in name).lstrip("_")
    if not snake.endswith("s"):
        snake += "s"
    return snake


def generate_schema_sql(entities: list[dict], app_name: str) -> str:
    statements = [f"-- {app_name} database schema (generated by AgentForge Database Agent)"]
    entity_names = {e["name"] for e in entities}
    table_by_class = {e["name"].lower(): _table_name(e) for e in entities}
    for entity in entities:
        table = _table_name(entity)
        cols = ["    id SERIAL PRIMARY KEY"]
        fks = []
        for fname, ftype in entity.get("fields", []):
            if fname.endswith("_id") and ftype == "integer":
                target_table = table_by_class.get(fname[:-3].lower())
                if target_table and fname[:-3].capitalize() in entity_names:
                    fks.append(f"    FOREIGN KEY ({fname}) REFERENCES {target_table}(id)")
                    continue
            sql_type = FIELD_SQL_TYPES.get(ftype, "VARCHAR(255)")
            statements_stub = f"    {fname} {sql_type}"
            cols.append(statements_stub)
        for fk in fks:
            cols.append(fk)
        statements.append(f"CREATE TABLE IF NOT EXISTS {table} (\n" + ",\n".join(cols) + "\n);")
    statements.append("CREATE INDEX IF NOT EXISTS idx_generic_created ON %s;" % _table_name(entities[0]))
    return "\n\n".join(statements) + "\n"


def generate_seed_sql(entities: list[dict], app_name: str) -> str:
    lines = [f"-- {app_name} seed data (generated by AgentForge Database Agent)"]
    for entity in entities[:2]:
        table = _table_name(entity)
        fields = [f[0] for f in entity.get("fields", []) if not f[0].endswith("_id")][:4]
        if not fields:
            continue
        sample = {
            "name": "'Sample Record'",
            "title": "'Sample Record'",
            "email": "'sample@example.com'",
            "description": "'Generated seed record'",
            "status": "'active'",
        }
        values = ", ".join(sample.get(f, f"'{f}_value'") for f in fields)
        cols = ", ".join(fields)
        lines.append(f"INSERT INTO {table} ({cols}) VALUES ({values});")
    return "\n".join(lines) + "\n"


def generate_database_py(app_name: str) -> str:
    return f'''"""Database engine and session for {app_name} (generated by AgentForge Database Agent)."""

import os

from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker

from models import Base

_engine_url = os.environ.get("DATABASE_URL", "sqlite:///./data/app.db")
if _engine_url.startswith("sqlite"):
    os.makedirs("data", exist_ok=True)
engine = create_engine(
    _engine_url,
    connect_args={{"check_same_thread": False}} if _engine_url.startswith("sqlite") else {{}},
)
SessionLocal = sessionmaker(bind=engine, autoflush=False, expire_on_commit=False)


def init_db():
    Base.metadata.create_all(bind=engine)


def get_db():
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()
'''


def generate_models_py(entities: list[dict], app_name: str) -> str:
    class_defs = []
    entity_names = {e["name"] for e in entities}
    table_by_class = {e["name"].lower(): _table_name(e) for e in entities}
    for entity in entities:
        class_name = entity["name"]
        table = _table_name(entity)
        cols = ["    id = Column(Integer, primary_key=True)"]
        for fname, ftype in entity.get("fields", []):
            if fname.endswith("_id") and ftype == "integer":
                target_table = table_by_class.get(fname[:-3].lower())
                if target_table and fname[:-3].capitalize() in entity_names:
                    cols.append(f"    {fname} = Column(Integer, ForeignKey('{target_table}.id'))")
                    continue
            sa_type = FIELD_SA_TYPES.get(ftype, "String(255)")
            cols.append(f"    {fname} = Column({sa_type})")
        class_defs.append(
            f"class {class_name}(Base):\n    __tablename__ = \"{table}\"\n" + "\n".join(cols)
        )
    return f'''"""SQLAlchemy models for {app_name} (generated by AgentForge Database Agent)."""

from sqlalchemy import Column, Integer, String, Text, Float, DateTime, ForeignKey
from sqlalchemy.orm import declarative_base, relationship

Base = declarative_base()

{chr(10).join(class_defs)}
'''


def generate_database_files(entities: list[dict], app_name: str) -> dict[str, str]:
    from app.services.codegen.entities import normalize_entities

    entities = normalize_entities(entities)
    return {
        "database/schema.sql": generate_schema_sql(entities, app_name),
        "database/seed.sql": generate_seed_sql(entities, app_name),
        "backend/models.py": generate_models_py(entities, app_name),
        "backend/database.py": generate_database_py(app_name),
    }
