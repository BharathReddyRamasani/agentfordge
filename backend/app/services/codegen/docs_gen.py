"""Documentation Agent codegen: generates real project documentation from structured inputs."""

import json
from datetime import datetime, timezone


def generate_docs_files(
    analysis: dict, plan: dict, architecture: dict, entities: list[dict], app_name: str
) -> dict[str, str]:
    from app.services.codegen.entities import normalize_entities

    entities = normalize_entities(entities)
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    features = "\n".join(f"- **{f.get('name', '')}**: {f.get('description', '')}" for f in analysis.get("essential_features", []))
    roles = ", ".join(analysis.get("user_roles", []))
    flow = "\n".join(f"{i+1}. {step}" for i, step in enumerate(analysis.get("primary_user_flow", [])))
    frs = "\n".join(f"- **{r.get('id', '')} — {r.get('title', '')}**: {r.get('description', '')}" for r in analysis.get("functional_requirements", []))
    nfrs = "\n".join(f"- **{r.get('id', '')} — {r.get('title', '')}**: {r.get('description', '')}" for r in analysis.get("non_functional_requirements", []))
    endpoints = "\n".join(
        f"| `{e.get('method', 'GET')}` | `{e.get('path', '')}` | {e.get('description', '')} | {'Yes' if e.get('auth_required', True) else 'No'} |"
        for e in architecture.get("api_endpoints", [])
    )
    entity_rows = "\n".join(
        f"| `{e['name']}` | {', '.join(f'{f[0]} ({f[1]})' for f in e.get('fields', []))} |"
        for e in entities
    )
    modules = "\n".join(f"- {m}" for m in architecture.get("modules", []))
    stack = plan.get("full_application_plan", {}).get("stack", {})

    readme = f"""# {app_name}

> {analysis.get('core_value_proposition', '')}

**{app_name}** was autonomously generated by **AgentForge** — an autonomous multi-agent AI
software engineering platform. The application was built from an approved, human-validated
prototype following the full engineering workflow (architecture → database → backend →
frontend → integration → testing → review → security → documentation → deployment).

## Overview

{analysis.get('purpose', '')}

**Target users:** {analysis.get('target_users', []) and ', '.join(analysis.get('target_users', []))}

## Features

{features}

## User Roles

{roles}

## Primary User Flow

{flow}

## Technology Stack

| Layer | Technology |
|---|---|
| Frontend | {stack.get('frontend', 'React 18 + Vite + TypeScript + Tailwind CSS')} |
| Backend | {stack.get('backend', 'Python FastAPI')} |
| Database | {stack.get('database', 'PostgreSQL / SQLite')} |

## Quick Start

```bash
# 1. Install backend dependencies
pip install -r backend/requirements.txt

# 2. Start the backend API (it also serves the built React frontend)
python -m uvicorn main:app --app-dir backend --port 8001

# 3. Open the full application
# http://localhost:8001  (React + Vite + TypeScript production build)
```

Frontend development mode (hot reload, API proxied to :8001):

```bash
cd frontend
npm install
npm run dev    # http://localhost:5173
```

The API is documented at `http://localhost:8001/docs` (Swagger UI).

## Project Structure

```
application/
├── backend/     # FastAPI API (models, schemas, auth, CRUD, SPA serving)
├── frontend/    # React 18 + Vite + TypeScript + Tailwind source (src/)
│   └── dist/    # Production build generated during engineering
├── database/    # schema.sql + seed.sql
├── tests/       # Pytest functional/API test suite
├── docs/        # Detailed guides
└── README.md
```

## Running Tests

```bash
cd <application-root>
python -m pytest tests/ -v
```

## Documentation

- [Architecture](docs/ARCHITECTURE.md)
- [API Reference](docs/API.md)
- [Database Schema](docs/DATABASE.md)
- [User Guide](docs/USER_GUIDE.md)
- [Deployment](docs/DEPLOYMENT.md)

---
*Generated by AgentForge on {ts}.*
"""

    api_doc = f"""# {app_name} — API Reference

Base URL: `http://localhost:8001`

All responses are JSON. Endpoints marked **Yes** in Auth require an
`Authorization: Bearer <token>` header (token obtained from `POST /api/auth/login`).

| Method | Path | Description | Auth |
|---|---|---|---|
{endpoints}

## Authentication Example

```bash
curl -X POST http://localhost:8001/api/auth/register \\
  -H "Content-Type: application/json" \\
  -d '{"{"}"name": "Jane", "email": "jane@example.com", "password": "secret123"{"}"}'

curl -X POST http://localhost:8001/api/auth/login \\
  -H "Content-Type: application/json" \\
  -d '{"{"}"email": "jane@example.com", "password": "secret123"{"}"}'
```

## Error Schema

Errors return `{{"detail": "<message>"}}` with appropriate HTTP status codes
(401 unauthenticated, 404 not found, 409 conflict, 422 validation).
"""

    db_doc = f"""# {app_name} — Database Schema

Generated by the AgentForge Database Agent. Consistent with the approved
requirements, prototype and architecture.

| Entity | Fields |
|---|---|
{entity_rows}

## Applying the Schema

```bash
psql -d <database> -f database/schema.sql
psql -d <database> -f database/seed.sql
```

The backend also auto-creates tables on startup via SQLAlchemy (`init_db`).
"""

    arch_doc = f"""# {app_name} — Architecture

## Summary

{architecture.get('summary', '')}

## Frontend

{architecture.get('frontend_architecture', '')}

## Backend

{architecture.get('backend_architecture', '')}

## Database

{architecture.get('database_architecture', '')}

## Authentication

{architecture.get('auth_architecture', '')}

## Integration

{architecture.get('integration_architecture', '')}

## Deployment

{architecture.get('deployment_architecture', '')}

## Modules

{modules}
"""

    user_guide = f"""# {app_name} — User Guide

## Getting Started

1. Start the backend API (see README Quick Start).
2. Open the frontend in your browser.
3. Register an account, then log in.

## Roles

{roles}

## Walkthrough

{flow}

## Troubleshooting

- **Cannot connect**: ensure the backend is running on port 8001.
- **401 errors**: your session expired — log in again.
"""

    deploy_doc = f"""# {app_name} — Deployment

## Docker

```bash
docker compose up --build
```

The application API starts on port 8001 with a PostgreSQL database service.

## Configuration

| Variable | Purpose | Default |
|---|---|---|
| `DATABASE_URL` | Database connection string | `sqlite:///./data/app.db` |
| `JWT_SECRET` | Token signing secret | `dev-secret-change-me` |

> Set a strong `JWT_SECRET` in production. Never commit real secrets.

---
*Generated by AgentForge on {ts}.*
"""

    return {
        "README.md": readme,
        "docs/API.md": api_doc,
        "docs/DATABASE.md": db_doc,
        "docs/ARCHITECTURE.md": arch_doc,
        "docs/USER_GUIDE.md": user_guide,
        "docs/DEPLOYMENT.md": deploy_doc,
    }
