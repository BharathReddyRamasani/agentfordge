"""Testing Agent codegen: generates a real pytest suite for the generated application,
derived from the approved requirements, entities and API design."""

from app.services.codegen.backend_app import _plural


_SAMPLE_VALUES = {
    "string": "sample text",
    "text": "sample text",
    "integer": 1,
    "float": 1.5,
    "date": "2024-01-01",
    "datetime": "2024-01-01T00:00:00",
    "boolean": True,
}


def _payload_str(entity: dict) -> str:
    parts = []
    for fname, ftype in entity.get("fields", []):
        if fname in ("password_hash", "password") or fname.endswith("_id"):
            continue
        parts.append(f'"{fname}": {_SAMPLE_VALUES.get(ftype, 1)!r}')
    return ", ".join(parts)


def generate_conftest_py() -> str:
    return '''"""Test configuration for the generated application (generated by AgentForge Testing Agent)."""

import os
import pathlib
import sys
import tempfile

BACKEND_DIR = pathlib.Path(__file__).resolve().parents[1] / "backend"
sys.path.insert(0, str(BACKEND_DIR))

_tmp_db = pathlib.Path(tempfile.mkdtemp()) / "generated_test.db"
os.environ["DATABASE_URL"] = f"sqlite:///{_tmp_db.as_posix()}"
os.environ["JWT_SECRET"] = "test-secret"

import pytest  # noqa: E402
from fastapi.testclient import TestClient  # noqa: E402


@pytest.fixture()
def client():
    import main
    from database import init_db

    init_db()
    with TestClient(main.app) as c:
        yield c


@pytest.fixture()
def auth_headers(client):
    import uuid

    email = f"test_{uuid.uuid4().hex[:8]}@example.com"
    client.post("/api/auth/register", json={"name": "Test User", "email": email, "password": "testpass123"})
    resp = client.post("/api/auth/login", json={"email": email, "password": "testpass123"})
    token = resp.json()["access_token"]
    return {"Authorization": f"Bearer {token}"}
'''


def generate_test_app_py(entities: list[dict], app_name: str) -> str:
    crud_tests = []
    for e in entities[:3]:
        name = e["name"]
        # Same contract as the backend routes and the React ENTITIES config: table name.
        plural = e.get("table") or _plural(name)
        fields = [f for f, _ in e.get("fields", []) if f not in ("password_hash",) and not f.endswith("_id")]
        if not fields:
            continue
        payload_str = _payload_str(e)
        crud_tests.append(f'''

def test_create_and_list_{plural}(client, auth_headers):
    payload = {{{payload_str}}}
    resp = client.post("/api/{plural}", json=payload, headers=auth_headers)
    assert resp.status_code == 201, resp.text
    created = resp.json()
    assert created["id"] is not None
    resp = client.get("/api/{plural}", headers=auth_headers)
    assert resp.status_code == 200
    assert any(item["id"] == created["id"] for item in resp.json())


def test_get_update_delete_{plural[:-1]}(client, auth_headers):
    payload = {{{payload_str}}}
    created = client.post("/api/{plural}", json=payload, headers=auth_headers).json()
    item_id = created["id"]
    resp = client.get(f"/api/{plural}/{{item_id}}", headers=auth_headers)
    assert resp.status_code == 200
    update_payload = dict(payload)
    resp = client.put(f"/api/{plural}/{{item_id}}", json=update_payload, headers=auth_headers)
    assert resp.status_code == 200
    resp = client.delete(f"/api/{plural}/{{item_id}}", headers=auth_headers)
    assert resp.status_code == 204
    resp = client.get(f"/api/{plural}/{{item_id}}", headers=auth_headers)
    assert resp.status_code == 404
''')

    return f'''"""Functional/API tests for {app_name} (generated by AgentForge Testing Agent).
Tests validate that the generated application behaves according to the approved requirements."""

{"".join(crud_tests)}


def test_health(client):
    resp = client.get("/health")
    assert resp.status_code == 200
    assert resp.json()["status"] == "ok"


def test_register_login_me(client):
    import uuid

    email = f"flow_{{uuid.uuid4().hex[:8]}}@example.com"
    resp = client.post("/api/auth/register", json={{"name": "Flow User", "email": email, "password": "testpass123"}})
    assert resp.status_code == 201
    resp = client.post("/api/auth/login", json={{"email": email, "password": "testpass123"}})
    assert resp.status_code == 200
    token = resp.json()["access_token"]
    resp = client.get("/api/auth/me", headers={{"Authorization": f"Bearer {{token}}"}})
    assert resp.status_code == 200


def test_unauthorized_access_blocked(client):
    resp = client.get("/api/auth/me")
    assert resp.status_code == 401


def test_invalid_login_rejected(client):
    resp = client.post("/api/auth/login", json={{"email": "nobody@example.com", "password": "wrongpass123"}})
    assert resp.status_code == 401
'''


def generate_tests_files(entities: list[dict], app_name: str) -> dict[str, str]:
    from app.services.codegen.entities import normalize_entities

    entities = normalize_entities(entities)
    return {
        "tests/conftest.py": generate_conftest_py(),
        "tests/test_app.py": generate_test_app_py(entities, app_name),
    }
