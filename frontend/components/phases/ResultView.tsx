"use client";

import { useEffect, useState } from "react";
import { CheckCircle2, Download } from "lucide-react";
import { api } from "@/lib/api";
import { getToken } from "@/lib/auth";
import { useProject } from "@/store/project";
import { SectionCard, Spinner } from "@/components/common";
import type { DownloadPackage, TestRun } from "@/types";

const LABELS: Record<string, string> = {
  application: "Complete Application — React + Vite + TypeScript source (frontend + backend + database)",
  prototype: "Approved Prototype — final validated prototype version",
  docs: "Documentation — README, user guide, API docs, architecture docs",
  deployment: "Deployment Files — Docker, compose, environment files",
  full: "Complete Project Package — everything in one archive",
};

export function ResultView({ projectId }: { projectId: number }) {
  const project = useProject((s) => s.project);
  const tests = useProject((s) => s.tests);
  const agents = useProject((s) => s.agents);
  const [pkgs, setPkgs] = useState<DownloadPackage[]>([]);
  const [loading, setLoading] = useState(true);
  const token = getToken();

  useEffect(() => {
    if (!token) return;
    api.getDownloads(token, projectId).then(setPkgs).catch(() => {}).finally(() => setLoading(false));
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [projectId]);

  const lastTest: TestRun | undefined = tests[tests.length - 1];

  return (
    <div>
      <div className="mb-4 flex items-center gap-2">
        <CheckCircle2 className="h-6 w-6 text-emerald-500" />
        <div>
          <h2 className="text-lg font-bold text-slate-900">Project Completed Successfully!</h2>
          <p className="text-sm text-slate-500">Your application has been generated, tested, and packaged.</p>
        </div>
      </div>
      <div className="grid gap-4 lg:grid-cols-3">
        <div className="lg:col-span-2">
          <SectionCard
            title="Live Application"
            subtitle="The full-scale production build (React + Vite + TypeScript frontend on the FastAPI backend) — interact with it right here."
            action={
              token ? (
                <a
                  href={api.applicationPreviewUrl(projectId, token)}
                  target="_blank"
                  rel="noreferrer"
                  className="rounded-lg border border-slate-300 px-3 py-1.5 text-xs font-medium text-slate-700 hover:bg-slate-50"
                >
                  Open in new tab
                </a>
              ) : undefined
            }
          >
            <div className="overflow-hidden rounded-xl border border-slate-200 bg-white">
              <iframe
                title="Full-scale application"
                src={token ? api.applicationPreviewUrl(projectId, token) : ""}
                sandbox="allow-scripts allow-forms allow-same-origin"
                className="h-[560px] w-full bg-white"
              />
            </div>
          </SectionCard>
          <SectionCard title="Download Artifacts" subtitle="Production packages generated by the autonomous workflow.">
            {loading ? (
              <Spinner />
            ) : (
              <div className="divide-y divide-slate-100">
                {pkgs.map((d) => (
                  <div key={d.kind} className="flex items-center justify-between gap-3 py-3">
                    <div>
                      <p className="text-sm font-semibold capitalize text-slate-800">{d.kind}</p>
                      <p className="text-xs text-slate-500">{LABELS[d.kind] ?? d.filename} · {(d.size / 1024).toFixed(1)} KB</p>
                    </div>
                    <a
                      href={token ? api.downloadUrl(projectId, d.kind, token) : "#"}
                      className="flex items-center gap-1.5 rounded-lg bg-indigo-600 px-3 py-1.5 text-xs font-medium text-white hover:bg-indigo-700"
                    >
                      <Download className="h-3.5 w-3.5" /> Download ZIP
                    </a>
                  </div>
                ))}
              </div>
            )}
          </SectionCard>
        </div>
        <SectionCard title="Project Summary">
          <div className="grid gap-2 text-sm">
            {[
              ["Project Name", project?.name ?? "—"],
              ["Status", "Completed"],
              ["Completed At", project?.updated_at ? new Date(project.updated_at).toLocaleString() : "—"],
              ["Total Agents Executed", String(new Set(agents.map((a) => a.agent)).size)],
              ["Test Cases Passed", lastTest ? `${lastTest.passed} / ${lastTest.total}` : "—"],
              ["Progress", `${project?.progress ?? 100}%`],
            ].map(([k, v]) => (
              <div key={k} className="flex justify-between gap-2 border-b border-slate-100 py-1.5 last:border-0">
                <span className="text-slate-500">{k}</span>
                <span className="text-right font-medium text-slate-800">{v}</span>
              </div>
            ))}
          </div>
        </SectionCard>
      </div>
    </div>
  );
}
